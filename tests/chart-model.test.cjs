'use strict';
const assert=require('node:assert/strict');
const {domain,navigate,nearest}=require('../arbitrage/web/chart-model.js');
const range={start_ms:1000,end_ms:11000,latest_ms:21000,earliest_ms:0};
assert.deepEqual(domain(range,20),[9000,11000]);
assert.equal(navigate(range,20,-1),9400);
assert.equal(navigate(range,20,1),12600);
assert.equal(navigate({...range,end_ms:21000},100,1),undefined);
assert.equal(navigate({...range,start_ms:20000,end_ms:20500},100,1),20900);
assert.equal(navigate({...range,start_ms:20000,end_ms:20900},100,1),null);
assert.equal(navigate({...range,earliest_ms:1000},100,-1),undefined);
assert.equal(navigate({...range,earliest_ms:null},20,-1),undefined);
const points=[{time:9000,value:2},{time:9500,value:null},{time:10000,value:0},{time:10500,value:Infinity}];
assert.equal(nearest(points,9980,[9500,11000],100).value,0);
assert.equal(nearest(points,9500,[9500,11000],100),null);
assert.equal(nearest(points,8000,[9500,11000],1900),null);
console.log('11 chart model assertions passed');
